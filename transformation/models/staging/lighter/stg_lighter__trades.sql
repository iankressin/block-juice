-- One Lighter trade, as the lighter-trades source loaded it from the daily S3 file. Each column is cast
-- and nothing is converted: a scaled integer keeps its scale and is named <name>_raw. slot_market_id
-- is the file's market_id, a slot Lighter reuses, not the API's market_id; public_market_index is the
-- API's market_id, null before 2026-08-20. trade_time comes from timestamp in ms, transaction_time
-- from Unix µs. Units and meanings are in catalog/vendors/lighter/NOTES.md and vendor.yaml.
select
    (data ->> 'id')::bigint as trade_id,
    to_timestamp((data ->> 'timestamp')::bigint / 1000.0) as trade_time,
    to_timestamp((data ->> 'transaction_time')::bigint / 1000000.0) as transaction_time,
    (data ->> 'created_at')::timestamptz as created_at,
    (data ->> 'updated_at')::timestamptz as updated_at,
    (data ->> 'l2_block_height')::bigint as block_number,
    data ->> 'tx_hash' as tx_hash,
    data ->> 'trade_type' as trade_type,
    (data ->> 'market_id')::integer as slot_market_id,
    (data ->> 'public_market_index')::integer as public_market_index,
    (data ->> 'is_maker_ask')::boolean as is_maker_ask,
    (data ->> 'ask_account_id')::bigint as ask_account_id,
    (data ->> 'bid_account_id')::bigint as bid_account_id,
    (data ->> 'ask_id')::bigint as ask_id,
    (data ->> 'bid_id')::bigint as bid_id,
    (data ->> 'ask_client_id')::bigint as ask_client_id,
    (data ->> 'bid_client_id')::bigint as bid_client_id,
    (data ->> 'ask_order_version')::bigint as ask_order_version,
    (data ->> 'bid_order_version')::bigint as bid_order_version,
    (data ->> 'size')::bigint as size_raw,
    (data ->> 'price')::bigint as price_raw,
    (data ->> 'usdc_amount')::bigint as usdc_amount_raw,
    (data ->> 'fee_account_id')::bigint as fee_account_id,
    (data ->> 'maker_fee')::integer as maker_fee_raw,
    (data ->> 'taker_fee')::integer as taker_fee_raw,
    (data ->> 'integrator_maker_fee')::integer as integrator_maker_fee_raw,
    (data ->> 'integrator_taker_fee')::integer as integrator_taker_fee_raw,
    (data ->> 'integrator_maker_fee_collector_index')::bigint as integrator_maker_fee_collector_index,
    (data ->> 'integrator_taker_fee_collector_index')::bigint as integrator_taker_fee_collector_index,
    (data ->> 'maker_position_size_before')::bigint as maker_position_size_before_raw,
    (data ->> 'taker_position_size_before')::bigint as taker_position_size_before_raw,
    (data ->> 'maker_entry_quote_before')::bigint as maker_entry_quote_before_raw,
    (data ->> 'taker_entry_quote_before')::bigint as taker_entry_quote_before_raw,
    (data ->> 'maker_initial_margin_fraction_before')::integer as maker_initial_margin_fraction_before_raw,
    (data ->> 'taker_initial_margin_fraction_before')::integer as taker_initial_margin_fraction_before_raw,
    (data ->> 'maker_position_sign_changed')::boolean as maker_position_sign_changed,
    (data ->> 'taker_position_sign_changed')::boolean as taker_position_sign_changed,
    (data ->> 'maker_allocated_margin_usdc_before')::bigint as maker_allocated_margin_usdc_before_raw,
    (data ->> 'maker_allocated_margin_usdc_after')::bigint as maker_allocated_margin_usdc_after_raw,
    (data ->> 'taker_allocated_margin_usdc_before')::bigint as taker_allocated_margin_usdc_before_raw,
    (data ->> 'taker_allocated_margin_usdc_after')::bigint as taker_allocated_margin_usdc_after_raw,
    (data ->> 'ask_account_pnl')::bigint as ask_account_pnl_raw,
    (data ->> 'bid_account_pnl')::bigint as bid_account_pnl_raw,
    _loaded_at
from {{ source('lighter', 'trades') }}
