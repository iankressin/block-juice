-- One Lighter trade of the accounts and markets in the lighter-trades source's addresses.json. market_id
-- is the public id the API uses. price, size and the positions are null for a binary option, which has
-- no market row; price_raw and size_raw keep the integers. size and positions are in base units,
-- *_ppm in parts per million of notional, and the other amounts in USDC.
select
    trade_id,
    trade_time,
    block_number,
    tx_hash,
    trade_type,
    market_id,
    slot_market_id,
    symbol,
    market_type,
    price,
    size,
    price_raw,
    size_raw,
    notional_usdc,
    is_maker_ask,
    maker_account_index,
    taker_account_index,
    taker_side,
    ask_account_index,
    bid_account_index,
    maker_fee_ppm,
    taker_fee_ppm,
    maker_fee_usdc,
    taker_fee_usdc,
    integrator_maker_fee_usdc,
    integrator_taker_fee_usdc,
    ask_order_index,
    bid_order_index,
    maker_position_before,
    taker_position_before,
    maker_entry_quote_before_usdc,
    taker_entry_quote_before_usdc,
    maker_position_sign_changed,
    taker_position_sign_changed,
    ask_account_pnl,
    bid_account_pnl
from {{ ref('int_lighter_trades') }}
